def _yield_ratios(counts: list[tuple[int, int]]) -> list[Fraction | None]:
    return [(Fraction(c, d) if d > 0 else None) for c, d in counts if c > 0]


def _counts(scenario: dict[str, Any]) -> list[tuple[int, int]]:
    return [tuple(pair) for pair in structure(scenario)["group_counts"]]


def _min_inverse_yield(counts: list[tuple[int, int]]) -> float:
    return min(d / c for c, d in counts if c > 0)


def _aggregate_ratio(counts: list[tuple[int, int]]) -> float:
    return sum(d for _, d in counts) / sum(c for c, _ in counts)


PREDICTORS: "OrderedDict[str, Callable[[dict[str, Any]], float]]" = OrderedDict(
    [
        ("pure_crit", lambda s: float(structure(s)["pure_crit"])),
        ("pure_crit_indicator", lambda s: float(structure(s)["pure_crit"] >= 1)),
        ("alpha", lambda s: float(structure(s)["alpha"])),
        (
            "distinct_yield_ratios",
            lambda s: float(
                len({("inf" if r is None else r) for r in _yield_ratios(_counts(s))})
            ),
        ),
        (
            "pure_distractor_mass",
            lambda s: sum(d for c, d in _counts(s) if c == 0)
            / max(1, sum(d for _, d in _counts(s))),
        ),
        (
            "critical_mass_in_pure_groups",
            lambda s: sum(c for c, d in _counts(s) if d == 0)
            / max(1, sum(c for c, _ in _counts(s))),
        ),
        ("n_groups", lambda s: float(structure(s)["n_groups"])),
        ("min_inverse_yield", lambda s: _min_inverse_yield(_counts(s))),
        (
            "allocation_headroom",
            lambda s: _aggregate_ratio(_counts(s)) - _min_inverse_yield(_counts(s)),
        ),
        (
            "log_allocation_headroom",
            lambda s: math.log(
                (_aggregate_ratio(_counts(s)) + 1e-6)
                / (_min_inverse_yield(_counts(s)) + 1e-6)
            ),
        ),
        ("cone_bound", lambda s: 1.0 / max(c for c, _ in _counts(s))),
        (
            "group_size_dispersion",
            lambda s: float(np.std(structure(s)["group_sizes"], ddof=0)),
        ),
    ]
)

REFUTED_PREDICTORS = ("pure_crit", "pure_crit_indicator")


def predictor_values(scenario: dict[str, Any]) -> dict[str, float]:
    return {name: float(fn(scenario)) for name, fn in PREDICTORS.items()}


def split_family(names: list[str]) -> dict[str, list[str]]:
    """Frozen discovery/confirmation split by the committed seed."""

    rng = np.random.default_rng(SPLIT_SEED)
    order = rng.permutation(len(names))
    discovery = sorted(names[i] for i in order[:DISCOVERY_SIZE])
    confirmation = sorted(names[i] for i in order[DISCOVERY_SIZE:])
    return {"discovery": discovery, "confirmation": confirmation}
