def build_scenario(name: str, profile: tuple[tuple[int, int], ...]) -> dict[str, Any]:
    """Emit a scenario from a tie-group profile, by the geometry-v2 rule.

    Positions are assigned to groups in profile order and in ascending index
    order; critical positions precede distractors within a group; features are
    one-hot group indicators; critical-bearing groups are ranked by first
    position and group ``j`` assigns target action ``j % A`` to all of its
    critical positions, which makes every scenario realizable by construction.
    """

    horizon = sum(c + d for c, d in profile)
    features = [[0] * len(profile) for _ in range(horizon)]
    critical_positions: list[int] = []
    critical_by_group: list[list[int]] = []

    position = 0
    for column, (n_crit, n_distr) in enumerate(profile):
        members: list[int] = []
        for _ in range(n_crit):
            features[position][column] = 1
            critical_positions.append(position)
            members.append(position)
            position += 1
        for _ in range(n_distr):
            features[position][column] = 1
            position += 1
        critical_by_group.append(members)

    targets: dict[int, int] = {}
    rank = 0
    for members in critical_by_group:
        if not members:
            continue
        for member in members:
            targets[member] = rank % N_ACTIONS
        rank += 1

    minimum_matches = max(
        1, int(math.ceil(len(critical_positions) * MINIMUM_MATCHES_FRACTION))
    )
    return OrderedDict(
        [
            ("name", name),
            ("environment", "threshold"),
            ("horizon", horizon),
            ("n_actions", N_ACTIONS),
            ("critical_positions", critical_positions),
            ("target_actions", [targets[k] for k in critical_positions]),
            ("minimum_matches", minimum_matches),
            (
                "initial_policy",
                [[1.0 / N_ACTIONS] * N_ACTIONS for _ in range(horizon)],
            ),
            ("features", features),
            ("iterations", ITERATIONS),
            ("group_size", GROUP_SIZE),
        ]
    )


def sample_profile(rng: np.random.Generator) -> tuple[tuple[int, int], ...] | None:
    """One random tie-group profile, or None if it violates a constraint."""

    horizon = int(rng.choice(HORIZONS))
    remaining = horizon
    sizes: list[int] = []
    while remaining > 0:
        size = int(rng.integers(1, min(remaining, 5) + 1))
        sizes.append(size)
        remaining -= size
    if len(sizes) < 2:
        return None

    profile = []
    for size in sizes:
        n_crit = int(rng.integers(0, size + 1))
        profile.append((n_crit, size - n_crit))

    total_critical = sum(c for c, _ in profile)
    total_distractor = sum(d for _, d in profile)
    if total_critical < 2 or total_distractor < 2:
        return None
    return tuple(profile)


def profile_key(profile: tuple[tuple[int, int], ...]) -> tuple:
    """Order-insensitive identity of a profile, for novelty and distinctness."""

    return (sum(c + d for c, d in profile), tuple(sorted(profile)))


def forbidden_profiles(configs: list[dict[str, Any]]) -> set[tuple]:
    """Profiles already used by geometry-v1 / geometry-v2, which may not recur."""

    seen: set[tuple] = set()
    for config in configs:
        for scenario in config["scenarios"]:
            critical = set(scenario["critical_positions"])
            counts = tuple(
                (
                    sum(1 for k in members if k in critical),
                    sum(1 for k in members if k not in critical),
                )
                for members in tie_groups(scenario)
            )
            seen.add(profile_key(counts))
    return seen


